s=part('fuselage')
bore=param('bearing_pedestal_bolt_bore',4.6)
diameter=param('fixed_axle_diameter',9.8)
top=param('axle_top_below_mast',58.8)
seat=param('lower_inner_race_seat_z',41.1)
seat_d=param('inner_race_support_diameter',12.6)
body=Pos(0,0,(s.roof_top+top)/2)*Cylinder(diameter/2,top-s.roof_top)
body=body.fuse(Pos(0,0,(s.roof_top+seat)/2)*Cylinder(seat_d/2,seat-s.roof_top))
body=body.cut(Pos(0,0,(s.roof_top+top)/2)*Cylinder(bore/2,top-s.roof_top+1))
body=body.cut(s.joint.through_cuts[1])
body.color=srgb('#FFFFFF')
publish('bearing_pedestal',body,'轴承内圈承重支座',material='petg')
