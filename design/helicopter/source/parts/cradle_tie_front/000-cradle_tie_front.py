c=part('battery_cradle')
width=param('tie_width',2.5)
thick=param('tie_installed_thickness',0.8)
outer_y=param('loop_depth_y',8.6)
outer_z=param('loop_height_z',7.6)
outer=RectangleRounded(outer_y,outer_z,1.0)
inner=RectangleRounded(outer_y-2*thick,outer_z-2*thick,.2)
body=Pos(c.tie_slot_x,21.1,-9.6)*extrude(Plane.YZ*(outer-inner),width/2,both=True)
body=body.fuse(Pos(c.tie_slot_x,25.9,-10)*Box(4.6,3.4,4.6))
assert len(body.solids())==1
publish('cradle_tie_front',body,'前托座扎带包络',role='reference',material='nylon')
